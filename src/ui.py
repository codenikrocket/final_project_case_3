"""
Модуль пользовательского интерфейса (консольного).
Обеспечивает взаимодействие с пользователем: запрос количества записей и формата экспорта.
"""

def get_user_input() -> dict:  # Функция для получения параметров от пользователя
    """
    Запрашивает у пользователя количество записей и формат.
    Возвращает словарь с настройками.
    """
    print("-" * 50)  # Вывод разделительной линии для визуального отделения
    print("Генератор тестовых данных (Case 3) запущен!")  # Приветственное сообщение
    print("-" * 50)  # Вывод нижней разделительной линии

    # Цикл валидации ввода количества записей
    while True:  # Бесконечный цикл, пока не получим корректный ответ
        count_str = input("Введите количество записей для генерации (например, 100): ")  # Запрос ввода с клавиатуры
        try:  # Начало блока обработки потенциальных ошибок
            count = int(count_str)  # Попытка преобразовать введенную строку в целое число
            if count <= 0:  # Проверка, что число положительное
                print("Ошибка: количество должно быть больше нуля.")  # Уведомление об ошибке
                continue  # Возврат в начало цикла while для повторного ввода
            break  # Выход из цикла, если преобразование прошло успешно и число > 0
        except ValueError:  # Перехват системной ошибки, если ввели текст вместо цифр
            print("Ошибка: пожалуйста, введите целое число (цифрами).")  # Понятное уведомление пользователю

    # Цикл валидации ввода формата экспорта
    while True:  # Бесконечный цикл для настройки формата
        # Запрос ввода, перевод в нижний регистр и удаление лишних пробелов по краям
        export_format = input("Выберите формат экспорта (csv, json или оба - all): ").lower().strip()  
        if export_format in ["csv", "json", "all"]:  # Проверка, что введенный текст есть в списке допустимых
            break  # Выход из цикла при совпадении
        print("Ошибка: допустимые значения - csv, json, all.")  # Сообщение об ошибке при опечатке

    return {  # Возврат итогового словаря с собранными настройками
        "count": count,  # Запись количества
        "format": export_format  # Запись выбранного формата
    }


# Блок для быстрого тестирования работы модуля
if __name__ == "__main__":  # Проверка запуска файла напрямую
    user_prefs = get_user_input()  # Вызов нашей функции опроса
    # Красивый вывод итогового словаря с подтверждением выбора
    print(f"\n[Успех] Вы выбрали генерацию {user_prefs['count']} записей в формате '{user_prefs['format']}'.")